#!/usr/bin/env ruby
# Generates typed C# node classes and a binary-serialization loader from
# prism's config.yml — the same approach JRuby uses for its Java loader.
#
#   ruby generate.rb [path/to/prism/config.yml] [output-dir]
#
# Re-run when upgrading the vendored prism (the loader validates the
# serialization version at runtime, so drift fails loudly).
require "yaml"

config_path = ARGV[0] || File.expand_path("../../../prism/config.yml", __dir__)
out_dir = ARGV[1] || File.expand_path("Generated", __dir__)
config = YAML.load_file(config_path)
nodes = config.fetch("nodes")
flags = config.fetch("flags")

def pascal(name)
  name.split("_").map(&:capitalize).join
end

def cs_type(field)
  case field.fetch("type")
  when "node" then "PmNode"
  when "node?" then "PmNode"
  when "node[]" then "PmNode[]"
  when "string" then "byte[]"   # prism string fields are raw bytes
  when "constant" then "string"
  when "constant?" then "string"
  when "constant[]" then "string[]"
  when "location" then "PmLocation"
  when "location?" then "PmLocation?"
  when "uint8" then "byte"
  when "uint32" then "uint"
  when "integer" then "System.Numerics.BigInteger"
  when "double" then "double"
  else raise "unknown field type #{field["type"]}"
  end
end

def cs_reader(field)
  # node, node? and node[] fields are popped off the node stack instead (see LoadNodes)
  case field.fetch("type")
  when "string" then "LoadStringBytes()"
  when "constant" then "LoadConstant()"
  when "constant?" then "LoadOptionalConstant()"
  when "constant[]" then "LoadConstantList()"
  when "location" then "LoadLocation()"
  when "location?" then "LoadOptionalLocation()"
  when "uint8" then "LoadByte()"
  when "uint32" then "LoadVarUInt()"
  when "integer" then "LoadInteger()"
  when "double" then "LoadDouble()"
  end
end

def field_name(node, field)
  name = pascal(field.fetch("name"))
  name == node.fetch("name") ? name + "Field" : name
end

require "stringio"

# ---- PrismNodes.Generated.cs ----
nodes_cs = StringIO.new
nodes_cs << <<~CS
  // <auto-generated> generated by generate.rb from prism config.yml — do not edit </auto-generated>
  namespace IronRuby.Prism.Ast {
      public readonly struct PmLocation {
          public readonly int Start;
          public readonly int Length;
          public PmLocation(int start, int length) { Start = start; Length = length; }
      }

      public abstract class PmNode {
          public uint NodeId;
          public int StartOffset;
          public int Length;
          public uint Flags;

          // common flags (bits 0-1); node-specific flags start at bit 2
          public bool IsNewLine { get { return (Flags & 1u) != 0; } }
          public bool IsStaticLiteral { get { return (Flags & 2u) != 0; } }
      }

CS
flags.each do |flag_set|
  nodes_cs << "    public static class #{flag_set.fetch("name")} {\n"
  flag_set.fetch("values").each_with_index do |value, i|
    nodes_cs << "        public const uint #{pascal(value.fetch("name").downcase)} = 1u << #{i + 2};\n"
  end
  nodes_cs << "    }\n\n"
end
nodes.each do |node|
  nodes_cs << "    public sealed class #{node.fetch("name")} : PmNode {\n"
  (node["fields"] || []).each do |field|
    nodes_cs << "        public #{cs_type(field)} #{field_name(node, field)};\n"
  end
  if node.fetch("name") == "DefNode"
    nodes_cs << <<-CS
        // Set by a loader asked for lazy method bodies: Body is null and the body's subtree is still
        // in the serialized buffer, DeferredBodyLength bytes at DeferredBodyOffset, for
        // PrismLoader.LoadDeferredBody; BodyContents is what the body holds (PrismLoader.Contents* bits).
        public IronRuby.Prism.PrismLoader DeferredBodyLoader;
        public int DeferredBodyOffset;
        public int DeferredBodyLength;
        public uint BodyContents;
    CS
  end
  nodes_cs << "    }\n\n"
end
nodes_cs << "}\n"

# ---- PrismLoader.Generated.cs ----
# prism serializes the tree in post-order (docs/serialization.md): the subtrees of a node's
# node/node?/node[] fields come first, in field order - an absent node? as a single 0 byte, a
# node[] as its elements - and then the node's own record: type, id, location, flags and every
# other field, with a node[] field reduced to its element count. The loader keeps a stack of the
# nodes it has built; a record pops its children off the top (the last child field first) and
# pushes the node. A DefNode's children are preceded by LAZY_MARKER and two raw uint32s, the byte
# length of the subtrees before its body and the byte length of the body, which is what lets the
# body be skimmed now and loaded later.
lazy_marker = 0xFF
raise "too many node types to reserve the lazy marker" if nodes.size >= lazy_marker

def child_field?(field)
  %w[node node? node[]].include?(field.fetch("type"))
end

def count_local(field)
  field.fetch("name").gsub(/_(\w)/) { $1.upcase } + "Count"
end

loader_cs = StringIO.new
loader_cs << <<~CS
  // <auto-generated> generated by generate.rb from prism config.yml — do not edit </auto-generated>
  using IronRuby.Prism.Ast;

  namespace IronRuby.Prism {
