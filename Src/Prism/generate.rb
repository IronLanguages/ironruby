def cs_skimmer(field)
  case field.fetch("type")
  when "string" then "SkipString();"
  when "constant", "constant?", "uint32" then "LoadVarUInt();"
  when "constant[]" then "SkipVarUIntList();"
  when "location" then "LoadLocation();"
  when "location?" then "LoadOptionalLocation();"
  when "uint8" then "_pos++;"
  when "integer" then "LoadInteger();"
  when "double" then "_pos += 8;"
  end
end

# what the bridge must not put off: bridged later, these would warn (or fail) late
eager_nodes = %w[DefinedNode SingletonClassNode ClassNode ModuleNode]
nodes.each_with_index do |node, index|
  name = node.fetch("name")
  fields = node["fields"] || []
  loader_cs << "                    case #{index + 1}: {\n"
  loader_cs << "                        _contents |= ContentsEager;\n" if eager_nodes.include?(name)
  loader_cs << "                        _contents |= ContentsUsesBlock;\n" if name == "YieldNode"
  fields.each do |field|
    case field.fetch("type")
    when "node", "node?" then next
    when "node[]" then loader_cs << "                        int #{count_local(field)} = (int)LoadVarUInt();\n"
    else
      if (name == "RegularExpressionNode" || name == "MatchLastLineNode") && field.fetch("name") == "unescaped"
        loader_cs << "                        SkipRegexpSource();\n"
      else
        loader_cs << "                        #{cs_skimmer(field)}\n"
      end
    end
  end
  children = fields.select { |f| child_field?(f) }
  if name == "DefNode"
    # A nested method's use of its block is its own; what forces the outer one eager is not.
    # The receiver is evaluated where the def is, so it is the outer method's.
    raise "DefNode's child fields changed" unless children.map { |f| f.fetch("name") } == %w[receiver parameters body]
    loader_cs << "                        uint inner = PopSkim() | PopSkim(); // body, parameters\n"
    loader_cs << "                        _contents |= (inner & ContentsEager) | PopSkim(); // receiver\n"
  else
    pending = []
    flush = lambda do
      next if pending.empty?
      fixed = pending.count(1)
      count = (pending.grep(String) + (fixed > 0 ? [fixed.to_s] : [])).join(" + ")
      loader_cs << "                        _contents |= #{count == "1" ? "PopSkim()" : "PopSkim(#{count})"};\n"
      pending.clear
    end
    children.reverse_each do |field|
      if (name == "SuperNode" || name == "ForwardingSuperNode") && field.fetch("name") == "block"
        flush.call
        # super with no block of its own passes the method's block on
        loader_cs << "                        if (PeekSkim() == SkimAbsent) _contents |= ContentsUsesBlock;\n"
        loader_cs << "                        _contents |= PopSkim();\n"
      elsif field.fetch("type") == "node[]"
        pending << count_local(field)
      else
        pending << 1
      end
    end
    flush.call
  end
  loader_cs << "                        break;\n"
  loader_cs << "                    }\n"
end
loader_cs << <<~CS
                      default:
