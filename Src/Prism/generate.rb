nodes.each_with_index do |node, index|
  name = node.fetch("name")
  fields = node["fields"] || []
  loader_cs << "                    case #{index + 1}: {\n"
  loader_cs << "                        var node = new #{name} {\n"
  loader_cs << "                            NodeId = nodeId, StartOffset = location.Start, Length = location.Length,\n"
  loader_cs << "                            Flags = LoadVarUInt(),\n"
  loader_cs << "                        };\n"
  fields.each do |field|
    case field.fetch("type")
    when "node", "node?" then next
    when "node[]" then loader_cs << "                        int #{count_local(field)} = (int)LoadVarUInt();\n"
    else loader_cs << "                        node.#{field_name(node, field)} = #{cs_reader(field)};\n"
    end
  end
  fields.select { |f| child_field?(f) }.reverse_each do |field|
    target = "node.#{field_name(node, field)}"
    if field.fetch("type") == "node[]"
      loader_cs << "                        #{target} = PopList(#{count_local(field)});\n"
    elsif name == "DefNode" && field.fetch("name") == "body"
      loader_cs << "                        PmNode body = Pop();\n"
      loader_cs << "                        if (body is DeferredBody deferred) {\n"
      loader_cs << "                            node.DeferredBodyLoader = this;\n"
      loader_cs << "                            node.DeferredBodyOffset = deferred.Offset;\n"
      loader_cs << "                            node.DeferredBodyLength = deferred.BodyLength;\n"
      loader_cs << "                            node.BodyContents = deferred.Contents;\n"
      loader_cs << "                        } else {\n"
      loader_cs << "                            #{target} = body;\n"
      loader_cs << "                        }\n"
    else
      loader_cs << "                        #{target} = Pop();\n"
    end
  end
  loader_cs << "                        Push(node);\n"
  loader_cs << "                        continue;\n"
  loader_cs << "                    }\n"
