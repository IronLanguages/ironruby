# The shapes of static library methods LibraryFunctionCall calls through their entry points: a return kind and the kinds of the
# parameters, R = a reference type, I = Int32, B = Boolean, D = Double, V = void (returns only). A function of reference
# parameters is called as one of object parameters - a reference is passed the same way whatever its type. The set: every
# arity up to LibraryFunctionCall.MaxArity of reference parameters only (three quarters of the library's overloads, and of
# those the prelude calls), and the commonest mixes with Int32, Boolean and Double parameters.

MAX_ARITY = 9

def shapes
  params = []
  (0..MAX_ARITY).each { |n| params << 'R' * n }
  (1..4).each { |n| n.times { |i| s = 'R' * n; s[i] = 'I'; params << s } }
  (1..5).each { |n| params << 'R' * (n - 1) + 'B' }
  (1..2).each { |n| n.times { |i| s = 'R' * n; s[i] = 'D'; params << s } }
  params.concat(%w[II DD ID DI])
  params.uniq!
  %w[R I B D V].flat_map { |r| params.map { |p| "#{r}:#{p}" } }
end

CLR = { 'R' => 'object', 'I' => 'int', 'B' => 'bool', 'D' => 'double', 'V' => 'void' }

def arg(kind, i)
  kind == 'R' ? "a[#{i}]" : "(#{CLR[kind]})a[#{i}]"
end

def call(shape)
  r, ps = shape.split(':', 2)
  ps ||= ''
  types = (ps.chars + [r]).map { |k| CLR[k] }.join(', ')
  invoke = "((delegate*<#{types}>)f)(#{ps.chars.each_with_index.map { |k, i| arg(k, i) }.join(', ')})"
  case r
  when 'R' then "return #{invoke};"
  when 'I' then "return ScriptingRuntimeHelpers.Int32ToObject(#{invoke});"
  when 'B' then "return ScriptingRuntimeHelpers.BooleanToObject(#{invoke});"
  when 'D' then "return #{invoke};"
  when 'V' then "#{invoke}; return null;"
  end
end

