#!/usr/bin/env ruby
# Generates the two halves of the rbs AST bridge from the rbs gem's config.yml:
#
#   native/rbs_ironruby_nodes.inc  C, compiled into librbs: writes each AST node the
#                                  parser built into IronRuby's byte stream
#   RbsNodes.Generated.cs          C#, read back by RbsDeserializer: the Ruby class and
#                                  the keyword names for each node type
#
#   ruby Src/Libraries/Rbs/generate.rb path/to/rbs-<version>/config.yml
#
# config.yml is what rbs's own templates/ext/rbs_extension/ast_translation.c.erb is
# rendered from, and this mirrors that template: a node becomes `Class.new(**h)` with
# `location:` first (unless expose_location is false), then its fields in config order,
# and RBS::AST::TypeParam.resolve_variables is called on `type_params` first wherever a
# node has them.  The nodes the template special-cases (expose_to_ruby: false, plus
# RBS::Keyword and RBS::AST::Symbol, which are not in config.yml) are special-cased in
# rbs_ironruby.c instead.
#
# Re-run, and rebuild librbs (Util/build-librbs.sh), when moving to another rbs release.
require "yaml"

config_path = ARGV[0] or abort "usage: ruby #{$0} path/to/rbs/config.yml"
here = __dir__
nodes = YAML.load_file(config_path).fetch("nodes")

def snake(ruby_name)
  ruby_name.split("::").map {|seg|
    seg.match?(/\A[A-Z]+\z/) ? seg.downcase : seg.gsub(/([a-z\d])([A-Z])/, '\1_\2').downcase
  }.join("_")
end

exposed = nodes.reject {|n| n["expose_to_ruby"] == false }

c = +<<~C
  /*----------------------------------------------------------------------------*/
  /* Generated by Src/Libraries/Rbs/generate.rb from rbs's config.yml.  Do not  */
  /* edit by hand.                                                              */
  /*----------------------------------------------------------------------------*/

  /* Writes the fields of an exposed node, in the order RbsNodes.Generated.cs     */
  /* names them.  Returns false for a node type that is not an exposed node.      */
  static bool rbs_ir_write_node_fields(rbs_ir_writer_t *w, rbs_node_t *instance) {
      switch (instance->type) {
C

exposed.each do |node|
  name = node.fetch("name")
  type = snake(name)
  c << "    case #{type.upcase}: {\n"
  fields = node["fields"] || []
  if node["expose_location"] != false || !fields.empty?
    c << "        #{type}_t *node = (#{type}_t *) instance;\n"
  end
  c << "        rbs_ir_write_location(w, node->base.location);\n" unless node["expose_location"] == false
  fields.each do |field|
    member = "node->#{field["c_name"] || field.fetch("name")}"
    c << case field.fetch("c_type")
         when "rbs_node_list" then "        rbs_ir_write_node_list(w, #{member});\n"
         when "rbs_hash" then "        rbs_ir_write_hash(w, #{member});\n"
         when "rbs_location" then "        rbs_ir_write_location(w, #{member});\n"
         when "rbs_location_list" then "        rbs_ir_write_location_list(w, #{member});\n"
         when "rbs_string" then "        rbs_ir_write_string(w, RBS_IR_STRING, &#{member});\n"
         when "bool" then "        rbs_ir_write_bool(w, #{member});\n"
         else "        rbs_ir_write_node(w, (rbs_node_t *) #{member});\n"
         end
  end
  c << "        return true;\n    }\n"
end
c << "    default:\n        return false;\n    }\n}\n"

cs = +<<~CS
  /* ****************************************************************************
   *
   * Generated by Src/Libraries/Rbs/generate.rb from rbs's config.yml.  Do not edit by hand.
   *
   * ***************************************************************************/

  namespace IronRuby.StandardLibrary.Rbs {
      internal static partial class RbsNodes {
          /// <summary>
          /// Indexed by rbs's enum rbs_node_type.  Null where the node is not built with
          /// Class.new(**fields): the C side writes those as plain values.
          /// </summary>
          internal static readonly RbsNodeInfo[] Table = {
              null,
  CS

# include/rbs/ast.h numbers the node types from 1 in the order of their Ruby names, not
# in config.yml order; rbs_ironruby_nodes.inc asserts each value at compile time.
numbered = nodes.sort_by {|n| n.fetch("name") }
numbered.each.with_index(1) do |node, id|
  name = node.fetch("name")
  if node["expose_to_ruby"] == false
    cs << "            null, // #{id} #{name}\n"
  else
    keys = []
    keys << "location" unless node["expose_location"] == false
    (node["fields"] || []).each {|f| keys << f.fetch("name") }
    resolve = keys.include?("type_params")
    path = name.split("::").map {|s| %("#{s}") }.join(", ")
    key_list = keys.map {|k| %("#{k}") }.join(", ")
    cs << "            new RbsNodeInfo(new[] { #{path} }, new string[] { #{key_list} }, #{resolve}), // #{id}\n"
  end
end
cs << "        };\n    }\n}\n"

# The C# table is indexed by these values, so a numbering that changes under it fails the
# librbs build instead of building the wrong classes.
c << "\n/* The enum values RbsNodes.Generated.cs is indexed by. */\n"
c << "#define RBS_IR_NODE_TYPE_COUNT #{nodes.size}\n"
numbered.each.with_index(1) do |n, id|
  c << "_Static_assert(#{snake(n["name"]).upcase} == #{id}, \"node type numbering\");\n"
end

File.binwrite(File.join(here, "native", "rbs_ironruby_nodes.inc"), c)
File.binwrite(File.join(here, "RbsNodes.Generated.cs"), cs)
puts "generated #{exposed.size} node types from #{config_path}"
